#!/usr/bin/env python3
"""Download the latest successful run of the Apify task `hiring-index-weekly` into data/jobs-latest.json.

Token: env APIFY_TOKEN (GitHub Actions secret) or, locally, the Apify CLI login (`apify auth token`).
Never prints the token.
Usage: python3 fetch.py [--run-id RUN_ID] [--resolve-boards]
  --resolve-boards  also rewrite data/boards.txt (resolved ats:slug per company → faster weekly runs)
"""
import json
import os
import subprocess
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).parent
TASK = "hiring-index-weekly"
TASK_ID = os.environ.get("APIFY_TASK_ID", "HHnGCgPYWVEiZn3uO")  # goldfoot~hiring-index-weekly


def token():
    t = os.environ.get("APIFY_TOKEN")
    if not t:
        t = subprocess.run(["apify", "auth", "token"], capture_output=True, text=True, check=True).stdout.strip().split()[-1]
    return t


def get(path, tok):
    req = urllib.request.Request(f"https://api.apify.com{path}", headers={"Authorization": f"Bearer {tok}"})
    with urllib.request.urlopen(req, timeout=120) as r:
        return json.loads(r.read())


def main():
    tok = token()
    if "--run-id" in sys.argv:  # comma-separated list → merged
        runs = [get(f"/v2/actor-runs/{r}", tok)["data"] for r in sys.argv[sys.argv.index('--run-id') + 1].split(",")]
    else:
        # Task ID (not username~name) so a scoped token without user-read permission works.
        runs = [get(f"/v2/actor-tasks/{TASK_ID}/runs/last?status=SUCCEEDED", tok)["data"]]
    items = []
    for run in runs:
        offset = 0
        while True:
            page = get(f"/v2/datasets/{run['defaultDatasetId']}/items?clean=1&offset={offset}&limit=5000"
                       "&fields=uid,ats,companySlug,companyName,title,department,location,locations,city,region,country,countryCode,"
                       "workplaceType,isRemote,salaryMin,salaryMax,salaryCurrency,salaryInterval,salaryText,postedAt,url,input", tok)
            items += page
            if len(page) < 5000:
                break
            offset += 5000
    run = runs[0]
    (ROOT / "data").mkdir(exist_ok=True)
    (ROOT / "data" / "jobs-latest.json").write_text(json.dumps(items, ensure_ascii=False))
    print(f"run {run['id']} ({run['startedAt'][:10]}): {len(items)} jobs")
    if "--resolve-boards" in sys.argv:
        boards = {}
        for j in items:
            if j.get("uid") and j.get("input"):
                ats, slug = j["uid"].split(":")[:2]
                boards.setdefault(j["input"], f"{ats}:{slug}")
        (ROOT / "data" / "boards.txt").write_text("# resolved job boards (input domain -> ats:slug); generated by fetch.py --resolve-boards\n"
                                                  + "".join(f"{v}  # {k}\n" for k, v in sorted(boards.items())))
        print(f"resolved {len(boards)} boards")


if __name__ == "__main__":
    main()
